//! `cargo xtask gen-defs`: the committed define constants (Plan/14 §10.9, WP-DATA-19; ADR-014).
//!
//! Input: the 17 `#define` headers of a real `Resource/` (`--resource DIR`, default `FLYFF_RESOURCE`),
//! read through `flyff-vfs` and scanned with `flyff-script`'s `Defines::scan_header`, i.e. by exactly the
//! code the server runs at start-up (first definition wins, `#if` ignored, `{` aborts a header).
//!
//! Output (committed, so builds never need Resource):
//!
//! * `crates/flyff-common/src/defs/<module>.rs`: `pub const NAME: u32 = value;` per header, in file order,
//! * `crates/flyff-common/src/defs/all.rs`: `ALL` (every constant, sorted by name) and `BY_HEADER`
//!   (file order, grouped by header),
//! * `crates/flyff-common/src/defs/manifest.json`: per header the file name, count and an xxh3 digest,
//! * `web/src/gen/defs/<module>.ts` and `index.ts`: `export const NAME = value;`.
//!
//! Values are the 32-bit patterns of the scanner's `i32` define values (`0x80000000L` is 2147483648);
//! only names (no text) are generated. `--check` regenerates in memory and fails on any difference.

use crate::proc::Ctx;
use anyhow::{Context, Result, bail};
use flyff_script::{DEFINE_HEADERS, Defines, Diagnostics};
use flyff_vfs::{Vfs, VfsConfig};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use xxhash_rust::xxh3::Xxh3;

/// Arguments of `cargo xtask gen-defs`.
#[derive(clap::Args, Debug, Clone, Default)]
pub struct Args {
    /// The original `Resource/` directory (default: `$FLYFF_RESOURCE`).
    #[arg(long)]
    pub resource: Option<PathBuf>,
    /// Regenerate in memory and fail on any difference with the committed files.
    #[arg(long)]
    pub check: bool,
}

/// Rust output directory.
const RUST_DIR: &str = "crates/flyff-common/src/defs";
/// TypeScript output directory.
const TS_DIR: &str = "web/src/gen/defs";

/// Module name of each header, in [`DEFINE_HEADERS`] order (Plan/14 §10.9).
pub const MODULES: [&str; 17] = [
    "define",
    "neuz",
    "quest",
    "job",
    "item",
    "world",
    "itemkind",
    "lang",
    "obj",
    "attribute",
    "skill",
    "text",
    "sound",
    "resdata",
    "wndstyle",
    "lordskill",
    "honor",
];

/// The definitions of one header in file order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HeaderDefs {
    /// Module name.
    pub module: &'static str,
    /// Header file name as the original code spells it.
    pub file: &'static str,
    /// `(name, value bit pattern)` in file order.
    pub entries: Vec<(String, u32)>,
}

/// Groups the winning definitions of `defines` by the header that defined them.
pub fn group_by_header(defines: &Defines) -> Vec<HeaderDefs> {
    let mut out: Vec<HeaderDefs> = DEFINE_HEADERS
        .iter()
        .zip(MODULES)
        .map(|(file, module)| HeaderDefs {
            module,
            file,
            entries: Vec::new(),
        })
        .collect();
    for (name, value) in defines.iter() {
        let Some((file, _line)) = defines.origin(name) else {
            continue;
        };
        if let Some(h) = out.iter_mut().find(|h| h.file == file) {
            h.entries.push((name.to_owned(), value as u32));
        }
    }
    out
}

/// One generated file: repository-relative path and content.
pub type Output = (String, String);

/// Renders every output file for the grouped definitions.
pub fn render(headers: &[HeaderDefs]) -> Vec<Output> {
    let mut files: Vec<Output> = Vec::new();
    let mut total = 0usize;
    for h in headers {
        files.push((format!("{RUST_DIR}/{}.rs", h.module), render_rust_module(h)));
        files.push((format!("{TS_DIR}/{}.ts", h.module), render_ts_module(h)));
        total += h.entries.len();
    }
    files.push((format!("{RUST_DIR}/all.rs"), render_all(headers)));
    files.push((format!("{TS_DIR}/index.ts"), render_ts_index(headers)));
    files.push((
        format!("{RUST_DIR}/manifest.json"),
        render_manifest(headers, total),
    ));
    files
}

fn banner(file: &str) -> String {
    format!(
        "@generated by `cargo xtask gen-defs` from the original `{file}` (Plan/14 §10.9). DO NOT EDIT."
    )
}

fn render_rust_module(h: &HeaderDefs) -> String {
    let mut s = String::with_capacity(h.entries.len() * 40 + 256);
    let _ = writeln!(s, "//! {}", banner(h.file));
    let _ = writeln!(
        s,
        "//! {} constants; values are the 32-bit patterns of the header's `#define` values.",
        h.entries.len()
    );
    s.push('\n');
    s.push_str("#![allow(non_upper_case_globals, missing_docs)]\n\n");
    for (name, value) in &h.entries {
        let _ = writeln!(s, "pub const {name}: u32 = {value};");
    }
    s
}

fn render_all(headers: &[HeaderDefs]) -> String {
    let mut sorted: Vec<(&str, u32)> = headers
        .iter()
        .flat_map(|h| h.entries.iter().map(|(n, v)| (n.as_str(), *v)))
        .collect();
    sorted.sort_unstable_by(|a, b| a.0.cmp(b.0));
    let mut s = String::with_capacity(sorted.len() * 60 * 2 + 1024);
    let _ = writeln!(s, "//! {}", banner("define headers"));
    s.push_str("//! `ALL` is sorted by name (byte order) so lookups can binary-search; `BY_HEADER` keeps file order.\n\n");
    s.push_str("#![allow(missing_docs)]\n\nuse super::HeaderDefs;\n\n");
    s.push_str("/// Every generated constant as `(name, value)`, sorted by name.\n#[rustfmt::skip]\npub const ALL: &[(&str, i64)] = &[\n");
    for (n, v) in &sorted {
        let _ = writeln!(s, "    ({n:?}, {v}),");
    }
    s.push_str("];\n\n");
    s.push_str("/// The same constants grouped by header, in file order.\n#[rustfmt::skip]\npub const BY_HEADER: &[HeaderDefs] = &[\n");
    for h in headers {
        let _ = writeln!(
            s,
            "    HeaderDefs {{\n        module: {:?},\n        file: {:?},\n        entries: &[",
            h.module, h.file
        );
        for (n, v) in &h.entries {
            let _ = writeln!(s, "            ({n:?}, {v}),");
        }
        s.push_str("        ],\n    },\n");
    }
    s.push_str("];\n");
    s
}

fn render_ts_module(h: &HeaderDefs) -> String {
    let mut s = String::with_capacity(h.entries.len() * 36 + 256);
    let _ = writeln!(s, "// {}", banner(h.file));
    s.push_str("/* eslint-disable */\n\n");
    for (name, value) in &h.entries {
        let _ = writeln!(s, "export const {name} = {value};");
    }
    s
}

fn render_ts_index(headers: &[HeaderDefs]) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "// {}", banner("define headers"));
    s.push_str("/* eslint-disable */\n\n");
    for h in headers {
        let _ = writeln!(s, "export * from './{}';", h.module);
    }
    s
}

/// xxh3 (64 bit, hex) of the `NAME=VALUE\n` lines of one header.
pub fn header_digest(h: &HeaderDefs) -> String {
    let mut x = Xxh3::new();
    for (n, v) in &h.entries {
        x.update(n.as_bytes());
        x.update(b"=");
        x.update(v.to_string().as_bytes());
        x.update(b"\n");
    }
    format!("{:016x}", x.digest())
}

fn render_manifest(headers: &[HeaderDefs], total: usize) -> String {
    let mut s = String::from("{\n  \"generator\": \"cargo xtask gen-defs\",\n  \"format\": 1,\n");
    let _ = writeln!(s, "  \"total\": {total},");
    s.push_str("  \"headers\": [\n");
    for (i, h) in headers.iter().enumerate() {
        let comma = if i + 1 == headers.len() { "" } else { "," };
        let _ = writeln!(
            s,
            "    {{ \"module\": {:?}, \"file\": {:?}, \"count\": {}, \"xxh3\": \"{}\" }}{comma}",
            h.module,
            h.file,
            h.entries.len(),
            header_digest(h)
        );
    }
    s.push_str("  ]\n}\n");
    s
}

/// Reads the 17 headers of `resource` and returns the grouped definitions.
pub fn read_headers(resource: &Path) -> Result<Vec<HeaderDefs>> {
    let vfs = Vfs::open_lenient(&VfsConfig::new(resource))
        .with_context(|| format!("open Resource tree {}", resource.display()))?;
    let mut defines = Defines::new();
    let mut diags = Diagnostics::new();
    let mut missing = Vec::new();
    for header in DEFINE_HEADERS {
        match vfs.read_text_auto(header) {
            Ok(d) => {
                defines.scan_header(&d.text, header, &mut diags);
            }
            Err(_) => missing.push(header),
        }
    }
    if !missing.is_empty() {
        bail!(
            "{} is not a complete Resource tree: missing header(s) {}",
            resource.display(),
            missing.join(", ")
        );
    }
    Ok(group_by_header(&defines))
}

/// The `gen` hook: runs `gen-defs` (or with `check` verifies the committed files) when `FLYFF_RESOURCE` points
/// at a Resource tree, otherwise skips with a note so machines without the proprietary data can still run
/// `cargo xtask check`.
pub fn gen_if_available(ctx: &Ctx, check: bool) -> Result<()> {
    let resource = std::env::var_os("FLYFF_RESOURCE")
        .map(PathBuf::from)
        .filter(|p| has_masquerade(p));
    match resource {
        Some(resource) => run(
            ctx,
            &Args {
                resource: Some(resource),
                check,
            },
        ),
        None => {
            println!("gen-defs: FLYFF_RESOURCE is unset or not a Resource tree; skipped");
            Ok(())
        }
    }
}

fn has_masquerade(dir: &Path) -> bool {
    std::fs::read_dir(dir).is_ok_and(|rd| {
        rd.filter_map(Result::ok).any(|e| {
            e.file_name()
                .to_string_lossy()
                .eq_ignore_ascii_case("masquerade.prj")
        })
    })
}

/// Writes (or with `check` verifies) the outputs.
pub fn run(ctx: &Ctx, args: &Args) -> Result<()> {
    let resource = match &args.resource {
        Some(p) => p.clone(),
        None => std::env::var_os("FLYFF_RESOURCE")
            .map(PathBuf::from)
            .context("pass --resource DIR or set FLYFF_RESOURCE")?,
    };
    let headers = read_headers(&resource)?;
    let total: usize = headers.iter().map(|h| h.entries.len()).sum();
    let files = render(&headers);
    let mut stale = Vec::new();
    for (rel, content) in &files {
        let path = ctx.path(rel);
        if std::fs::read_to_string(&path).ok().as_deref() == Some(content.as_str()) {
            continue;
        }
        if args.check {
            stale.push(rel.clone());
        } else {
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir)
                    .with_context(|| format!("create {}", dir.display()))?;
            }
            std::fs::write(&path, content).with_context(|| format!("write {rel}"))?;
            println!("wrote {rel}");
        }
    }
    if args.check {
        if !stale.is_empty() {
            bail!(
                "define constants are stale (run `cargo xtask gen-defs`): {}",
                stale.join(", ")
            );
        }
        println!(
            "gen-defs --check: {} constants in {} files up to date",
            total,
            files.len()
        );
    } else {
        println!("gen-defs: {total} constants from {}", resource.display());
    }
    Ok(())
}

//! `cargo xtask dev` (Plan/02 §7.2 mode A, WP-OPS-51 subset): a dev home in `.dev/`, the Rust server
//! (`fasttest` profile, `--dev`), and — once `web/` exists — the wasm watcher and the Vite dev server.
//! Ctrl-C reaches the whole process group; the children are also killed when this process exits.

// CLI output is this module's job.
#![allow(clippy::print_stdout, clippy::print_stderr)]

use crate::cmd::build_wasm;
use crate::proc::{Ctx, banner};
use anyhow::{Context, Result, bail};
use std::path::PathBuf;
use std::process::{Child, Command};

/// Arguments of `cargo xtask dev`.
#[derive(clap::Args, Debug, Clone)]
pub struct Args {
    /// The Resource folder (default: `$FLYFF_RESOURCE`).
    #[arg(long, value_name = "DIR")]
    pub resource: Option<PathBuf>,
    /// Use the generated synthetic Resource pack (not available yet).
    #[arg(long)]
    pub synthetic: bool,
    /// Do not start the Vite dev server.
    #[arg(long)]
    pub no_vite: bool,
    /// Do not start the wasm watcher.
    #[arg(long)]
    pub no_wasm_watch: bool,
    /// Port of the Rust server.
    #[arg(long, default_value_t = 8080)]
    pub port: u16,
}

struct Children(Vec<Child>);

impl Drop for Children {
    fn drop(&mut self) {
        for c in &mut self.0 {
            let _ = c.kill();
            let _ = c.wait();
        }
    }
}

/// The dev `flyff.toml`: dev surfaces on, debug logging for flyff crates, live NPC scripts from the
/// repository.
pub fn dev_config(npc_dir: &std::path::Path, port: u16) -> String {
    format!(
        "# Generated by `cargo xtask dev` (only written when missing).\n[net]\nbind = \"127.0.0.1:{port}\"\n\n[debug]\ndev_surfaces = true\n\n[log]\nlevel = \"info,flyff_server=debug,flyff_game=debug\"\n\n[paths]\nnpc_scripts_dir = {npc:?}\n",
        npc = npc_dir.to_string_lossy()
    )
}

/// Runs the dev environment.
pub fn run(ctx: &Ctx, args: &Args) -> Result<()> {
    banner("dev", 1, 4, "dev home");
    if args.synthetic {
        bail!(
            "--synthetic needs the synthetic Resource pack (WP-TEST-50), which does not exist yet; pass --resource DIR or set FLYFF_RESOURCE"
        );
    }
    let resource = args
        .resource
        .clone()
        .or_else(|| {
            std::env::var_os("FLYFF_RESOURCE")
                .filter(|v| !v.is_empty())
                .map(PathBuf::from)
        })
        .context("no Resource folder: pass --resource DIR or set FLYFF_RESOURCE")?;
    let home = ctx.path(".dev");
    std::fs::create_dir_all(&home)?;
    let cfg = home.join("flyff.toml");
    if !cfg.exists() {
        std::fs::write(&cfg, dev_config(&ctx.path("content/npc"), args.port))?;
        println!("    wrote {}", cfg.display());
    }
    let web = ctx.path("web/package.json").exists();

    banner("dev", 2, 4, "wasm (dev build)");
    if web {
        build_wasm::run(
            ctx,
            &build_wasm::Args {
                dev: true,
                ..build_wasm::Args::default()
            },
        )?;
    } else {
        println!("    web/ does not exist yet: only the Rust server (placeholder page) is started");
    }

    banner("dev", 3, 4, "start the processes");
    let mut children = Children(Vec::new());
    let path = ctx.path_env();
    let mut server = Command::new("cargo");
    server
        .args([
            "run",
            "-p",
            "flyff-server",
            "--profile",
            "fasttest",
            "--",
            "serve",
            "--dev",
            "--home",
        ])
        .arg(&home)
        .arg("--resource")
        .arg(&resource)
        .arg("--bind")
        .arg(format!("127.0.0.1:{}", args.port))
        .env("PATH", &path)
        .current_dir(&ctx.root);
    println!(
        "$ cargo run -p flyff-server --profile fasttest -- serve --dev --home {} --resource {} --bind 127.0.0.1:{}",
        home.display(),
        resource.display(),
        args.port
    );
    children.0.push(server.spawn().context("start the server")?);
    if web && !args.no_vite {
        let mut vite = Command::new("pnpm");
        vite.args(["--dir", "web", "dev"])
            .env("PATH", &path)
            .env("FLYFF_DEV_PORT", args.port.to_string())
            .current_dir(&ctx.root);
        println!("$ pnpm --dir web dev");
        children.0.push(vite.spawn().context("start vite")?);
    }
    if web && !args.no_wasm_watch {
        let mut watch = Command::new("cargo");
        watch
            .args(["xtask", "build-wasm", "--dev", "--watch"])
            .env("PATH", &path)
            .current_dir(&ctx.root);
        println!("$ cargo xtask build-wasm --dev --watch");
        children
            .0
            .push(watch.spawn().context("start the wasm watcher")?);
    }

    banner("dev", 4, 4, "running (Ctrl-C stops everything)");
    if web && !args.no_vite {
        println!(
            "Open http://localhost:5173/ (HMR); API/WebSocket are proxied to :{}",
            args.port
        );
    } else {
        println!("Open http://localhost:{}/", args.port);
    }
    // Wait for the server; when it ends, everything else is stopped by the guard.
    let status = children
        .0
        .first_mut()
        .context("no server process")?
        .wait()?;
    if !status.success() {
        bail!("the dev server exited with {status}");
    }
    Ok(())
}

//! `cargo xtask admin-caps [--check]` and `cargo xtask admin-dto [--check]` (Plan/25 §1.6, §11.10; WP-ADMIN-02): the
//! generated artefacts of the admin console contract.
//!
//! * `admin-caps` reads `crates/flyff-server/src/admin/caps.toml` (the capability table) and writes
//!   `crates/flyff-server/src/admin/caps.rs` (the `Cap` enum) and `web/src/admin/gen/caps.ts` (the same names for the
//!   browser). The generator is plain text assembly; it validates the table (unique dotted names, letters `L..P`).
//! * `admin-dto` runs the `admin-dto` example of `flyff-server` (feature `ts`), which writes
//!   `web/src/admin/gen/dto.ts` from the Rust DTOs of `admin::dto` with ts-rs.
//!
//! With `--check` nothing is written: stale files are named and the command fails. `cargo xtask gen [--check]`
//! runs both.

use crate::proc::{Ctx, Run};
use anyhow::{Context, Result, bail};
use std::collections::BTreeSet;
use std::fmt::Write as _;

/// Arguments of `cargo xtask admin-caps` / `admin-dto`.
#[derive(clap::Args, Debug, Clone, Default)]
pub struct Args {
    /// Verify instead of writing; exit 1 naming every stale file.
    #[arg(long)]
    pub check: bool,
}

const CAPS_TOML: &str = "crates/flyff-server/src/admin/caps.toml";
const CAPS_RS: &str = "crates/flyff-server/src/admin/caps.rs";
const CAPS_TS: &str = "web/src/admin/gen/caps.ts";

/// One row of `caps.toml`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CapRow {
    /// `view.dashboard`.
    pub name: String,
    /// `L`..`P`.
    pub min: char,
    /// One line.
    pub grants: String,
}

/// Parses and validates `caps.toml`.
pub fn parse_caps(text: &str) -> Result<Vec<CapRow>> {
    let doc: toml::Table = text.parse().context("caps.toml")?;
    let rows = doc
        .get("cap")
        .and_then(toml::Value::as_array)
        .context("caps.toml: no [[cap]] rows")?;
    let mut out = Vec::new();
    let mut seen = BTreeSet::new();
    for (i, row) in rows.iter().enumerate() {
        let t = row
            .as_table()
            .with_context(|| format!("caps.toml: row {} is not a table", i + 1))?;
        let name = t
            .get("name")
            .and_then(toml::Value::as_str)
            .with_context(|| format!("caps.toml: row {} has no name", i + 1))?;
        if name.is_empty()
            || !name
                .split('.')
                .all(|p| !p.is_empty() && p.bytes().all(|b| b.is_ascii_lowercase() || b == b'_'))
        {
            bail!("caps.toml: '{name}' is not a dotted lower-case name");
        }
        if !seen.insert(name.to_owned()) {
            bail!("caps.toml: duplicate capability '{name}'");
        }
        let min = t
            .get("min")
            .and_then(toml::Value::as_str)
            .with_context(|| format!("caps.toml: '{name}' has no min"))?;
        let mut chars = min.chars();
        let letter = match (chars.next(), chars.next()) {
            (Some(c @ 'L'..='P'), None) => c,
            _ => bail!("caps.toml: '{name}': min must be one letter L, M, N, O or P (got '{min}')"),
        };
        let grants = t
            .get("grants")
            .and_then(toml::Value::as_str)
            .with_context(|| format!("caps.toml: '{name}' has no grants text"))?;
        out.push(CapRow {
            name: name.to_owned(),
            min: letter,
            grants: grants.to_owned(),
        });
    }
    if out.is_empty() {
        bail!("caps.toml: empty");
    }
    Ok(out)
}

/// `view.chat.private` -> `ViewChatPrivate`.
fn variant(name: &str) -> String {
    let mut out = String::new();
    for part in name.split(['.', '_']) {
        let mut cs = part.chars();
        if let Some(c) = cs.next() {
            out.push(c.to_ascii_uppercase());
            out.push_str(cs.as_str());
        }
    }
    out
}

/// The `Authority` constant of a letter.
fn authority_const(letter: char) -> &'static str {
    match letter {
        'L' => "GAMEMASTER",
        'M' => "GAMEMASTER2",
        'N' => "GAMEMASTER3",
        'O' => "OPERATOR",
        _ => "ADMINISTRATOR",
    }
}

/// The text of `caps.rs`.
pub fn render_rs(rows: &[CapRow]) -> String {
    let mut s = String::new();
    s.push_str(
        "// @generated by `cargo xtask admin-caps` from `caps.toml`. Do not edit this file manually.\n\
         //! The capabilities of the admin console (Plan/25 §1.6): the minimum authority letter of each.\n\
         \n\
         #![cfg_attr(rustfmt, rustfmt::skip)]\n\
         \n\
         use flyff_common::gm::Authority;\n\
         \n\
         /// One capability of the admin console. Checked on the server for every route and subscription.\n\
         #[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]\n\
         pub enum Cap {\n",
    );
    for r in rows {
        let _ = writeln!(s, "    /// `{}`: {}.", r.name, r.grants);
        let _ = writeln!(s, "    {},", variant(&r.name));
    }
    s.push_str("}\n\nimpl Cap {\n");
    let _ = writeln!(s, "    /// Every capability, in table order.");
    let _ = writeln!(s, "    pub const ALL: [Cap; {}] = [", rows.len());
    for r in rows {
        let _ = writeln!(s, "        Cap::{},", variant(&r.name));
    }
    s.push_str("    ];\n\n");
    s.push_str("    /// The wire name (`view.dashboard`).\n    pub const fn name(self) -> &'static str {\n        match self {\n");
    for r in rows {
        let _ = writeln!(s, "            Cap::{} => {:?},", variant(&r.name), r.name);
    }
    s.push_str("        }\n    }\n\n");
    s.push_str("    /// One line for the staff overview.\n    pub const fn grants(self) -> &'static str {\n        match self {\n");
    for r in rows {
        let _ = writeln!(
            s,
            "            Cap::{} => {:?},",
            variant(&r.name),
            r.grants
        );
    }
    s.push_str("        }\n    }\n\n");
    s.push_str("    /// The lowest authority that holds the capability before `[admin.capabilities]` overrides.\n    pub const fn default_min(self) -> Authority {\n        match self {\n");
    for r in rows {
        let _ = writeln!(
            s,
            "            Cap::{} => Authority::{},",
            variant(&r.name),
            authority_const(r.min)
        );
    }
    s.push_str("        }\n    }\n\n");
    s.push_str("    /// The capability of a wire name.\n    pub fn parse(name: &str) -> Option<Cap> {\n        match name {\n");
    for r in rows {
        let _ = writeln!(
            s,
            "            {:?} => Some(Cap::{}),",
            r.name,
            variant(&r.name)
        );
    }
    s.push_str("            _ => None,\n        }\n    }\n}\n");
    s
}

/// The text of `caps.ts`.
pub fn render_ts(rows: &[CapRow]) -> String {
    let mut s = String::new();
    s.push_str(
        "// @generated by `cargo xtask admin-caps` from crates/flyff-server/src/admin/caps.toml. Do not edit this file manually.\n\
         // The capabilities of the admin console (Plan/25 §1.6). The server decides; the client only hides what\n\
         // `GET /admin/api/session` (`caps`) does not list.\n\n\
         export const CAPS = [\n",
    );
    for r in rows {
        let _ = writeln!(s, "  '{}',", r.name);
    }
    s.push_str("] as const;\n\nexport type Cap = (typeof CAPS)[number];\n\n");
    s.push_str("/** The lowest authority letter of each capability before the `[admin.capabilities]` overrides of the server. */\n");
    s.push_str("export const CAP_DEFAULT_MIN: Readonly<Record<Cap, string>> = {\n");
    for r in rows {
        let _ = writeln!(s, "  '{}': '{}',", r.name, r.min);
    }
    s.push_str("};\n\n");
    s.push_str("/** One line per capability (staff overview). */\nexport const CAP_GRANTS: Readonly<Record<Cap, string>> = {\n");
    for r in rows {
        let _ = writeln!(s, "  '{}': {},", r.name, serde_json_string(&r.grants));
    }
    s.push_str("};\n\n");
    s.push_str(
        "/** The authority letters in rank order (`D` lowest). */\n\
         export const AUTHORITY_ORDER = ['D', 'F', 'G', 'H', 'J', 'L', 'M', 'N', 'O', 'P', 'Z'] as const;\n\n\
         /** `true` when letter `a` is at least letter `min` (the legacy numeric comparison). */\n\
         export function authorityAtLeast(a: string, min: string): boolean {\n\
         \x20 return a.charCodeAt(0) >= min.charCodeAt(0);\n\
         }\n\n\
         export function isCap(name: string): name is Cap {\n\
         \x20 return (CAPS as readonly string[]).includes(name);\n\
         }\n",
    );
    s
}

/// A double-quoted string literal valid in TypeScript (JSON escapes).
fn serde_json_string(text: &str) -> String {
    let mut out = String::from("'");
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '\n' => out.push_str("\\n"),
            other => out.push(other),
        }
    }
    out.push('\'');
    out
}

/// Runs `admin-caps`.
pub fn caps(ctx: &Ctx, check: bool) -> Result<()> {
    let text = std::fs::read_to_string(ctx.path(CAPS_TOML)).context("read caps.toml")?;
    let rows = parse_caps(&text)?;
    let outputs = [(CAPS_RS, render_rs(&rows)), (CAPS_TS, render_ts(&rows))];
    let mut stale = Vec::new();
    for (rel, content) in &outputs {
        let path = ctx.path(rel);
        let current = std::fs::read_to_string(&path).ok();
        if current.as_deref() == Some(content.as_str()) {
            continue;
        }
        if check {
            stale.push(*rel);
        } else {
            if let Some(dir) = path.parent() {
                std::fs::create_dir_all(dir)
                    .with_context(|| format!("create {}", dir.display()))?;
            }
            std::fs::write(&path, content).with_context(|| format!("write {rel}"))?;
            println!("wrote {rel}");
        }
    }
    if !stale.is_empty() {
        bail!(
            "the generated admin capability files are stale: {}; run `cargo xtask admin-caps`",
            stale.join(", ")
        );
    }
    Ok(())
}

/// Runs `admin-dto` (the `admin-dto` example of `flyff-server`).
pub fn dto(ctx: &Ctx, check: bool) -> Result<()> {
    let mut cmd = Run::new(ctx, "cargo").args([
        "run",
        "--quiet",
        "-p",
        "flyff-server",
        "--features",
        "ts",
        "--example",
        "admin-dto",
        "--",
    ]);
    if check {
        cmd = cmd.arg("--check");
    }
    cmd.run().with_context(|| {
        if check {
            "web/src/admin/gen/dto.ts is stale; run `cargo xtask admin-dto`"
        } else {
            "admin-dto failed"
        }
    })
}

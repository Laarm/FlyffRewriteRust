//! TypeScript types from the bundle schemas (Plan/14 §10.7, feature `schema`).
//!
//! The types are generated from the same `schemars` documents as the JSON Schemas ([`super::schema`]), so the
//! Rust DTOs are the single source of truth. [`generate`] returns the files of `web/src/gen/bundles/`:
//!
//! * `types.ts`: one `export interface`/`type` per DTO, with the doc comments of the Rust items,
//! * `bundles.ts`: `RowTable<T>`, `BUNDLES` (name, schema version, load class), `BundleName`, `BundleDataMap`,
//!   `BundleEnvelope<N>`,
//! * `index.ts`: re-exports.
//!
//! The emitter handles the constructs the DTOs use: objects, arrays, tuples (`prefixItems`), fixed arrays,
//! maps, nullable and `anyOf` unions, string enums and constants, `$ref`, and the row-table extension keys.

use super::catalog::catalog;
use super::schema::bundle_schemas;
use serde_json::Value;
use std::collections::BTreeMap;
use std::fmt::Write as _;

/// A generated file: its name inside `web/src/gen/bundles/` and its text.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TsFile {
    /// The file name.
    pub name: &'static str,
    /// The content (ends with a newline).
    pub text: String,
}

const HEADER: &str = "// GENERATED by `cargo xtask gen-data-types` from the Rust bundle DTOs (flyff_data::bundle::types).\n// Do not edit: change the Rust types and regenerate (`cargo xtask gen`).\n\n";

/// The longest fixed-size array that becomes a tuple type.
const MAX_TUPLE: u64 = 8;

struct Ctx<'a> {
    /// All definitions by name.
    defs: &'a BTreeMap<String, Value>,
}

fn ref_name(r: &str) -> &str {
    r.rsplit('/').next().unwrap_or(r)
}

fn doc_comment(v: &Value, indent: &str) -> String {
    let Some(d) = v.get("description").and_then(Value::as_str) else {
        return String::new();
    };
    let d = d.replace("*/", "*\\/");
    let mut out = String::new();
    let lines: Vec<&str> = d.lines().collect();
    if let [only] = lines.as_slice() {
        let _ = writeln!(out, "{indent}/** {} */", only.trim());
    } else {
        let _ = writeln!(out, "{indent}/**");
        for l in lines {
            let _ = writeln!(out, "{indent} * {}", l.trim_end());
        }
        let _ = writeln!(out, "{indent} */");
    }
    out
}

fn quote(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| "\"\"".to_owned())
}

fn literal(v: &Value) -> String {
    match v {
        Value::String(s) => quote(s),
        other => other.to_string(),
    }
}

impl Ctx<'_> {
    /// The TypeScript type of a schema node.
    fn ty(&self, s: &Value) -> String {
        if let Some(r) = s.get("$ref").and_then(Value::as_str) {
            let name = ref_name(r);
            if let Some(def) = self.defs.get(name)
                && let Some(row) = def.get("x-flyff-row")
            {
                let inner = self.ty(row);
                let omit: Vec<String> = s
                    .get("x-flyff-omit")
                    .and_then(Value::as_array)
                    .map(|a| a.iter().filter_map(Value::as_str).map(quote).collect())
                    .unwrap_or_default();
                return if omit.is_empty() {
                    format!("RowTable<{inner}>")
                } else {
                    format!("RowTable<Omit<{inner}, {}>>", omit.join(" | "))
                };
            }
            return name.to_owned();
        }
        if let Some(c) = s.get("const") {
            return literal(c);
        }
        if let Some(e) = s.get("enum").and_then(Value::as_array) {
            return union(e.iter().map(literal));
        }
        for key in ["anyOf", "oneOf"] {
            if let Some(a) = s.get(key).and_then(Value::as_array) {
                return union(a.iter().map(|x| self.ty(x)));
            }
        }
        if let Some(all) = s.get("allOf").and_then(Value::as_array) {
            return all
                .iter()
                .map(|x| self.ty(x))
                .collect::<Vec<_>>()
                .join(" & ");
        }
        match s.get("type") {
            Some(Value::Array(types)) => union(
                types
                    .iter()
                    .filter_map(Value::as_str)
                    .map(|t| self.typed(t, s)),
            ),
            Some(Value::String(t)) => self.typed(t, s),
            _ => "unknown".to_owned(),
        }
    }

    fn typed(&self, t: &str, s: &Value) -> String {
        match t {
            "string" => "string".to_owned(),
            "integer" | "number" => "number".to_owned(),
            "boolean" => "boolean".to_owned(),
            "null" => "null".to_owned(),
            "array" => self.array(s),
            "object" => self.object(s),
            _ => "unknown".to_owned(),
        }
    }

    fn array(&self, s: &Value) -> String {
        if let Some(p) = s.get("prefixItems").and_then(Value::as_array) {
            let parts: Vec<String> = p.iter().map(|x| self.ty(x)).collect();
            return format!("[{}]", parts.join(", "));
        }
        let item = s
            .get("items")
            .map_or_else(|| "unknown".to_owned(), |i| self.ty(i));
        let (min, max) = (
            s.get("minItems").and_then(Value::as_u64),
            s.get("maxItems").and_then(Value::as_u64),
        );
        if let (Some(a), Some(b)) = (min, max)
            && a == b
            && (1..=MAX_TUPLE).contains(&a)
        {
            return format!("[{}]", vec![item; a as usize].join(", "));
        }
        if needs_parens(&item) {
            format!("({item})[]")
        } else {
            format!("{item}[]")
        }
    }

    fn object(&self, s: &Value) -> String {
        if let Some(props) = s.get("properties").and_then(Value::as_object)
            && !props.is_empty()
        {
            return self.inline_object(s, props);
        }
        if let Some(a) = s.get("additionalProperties").filter(|a| a.is_object()) {
            return format!("Record<string, {}>", self.ty(a));
        }
        "Record<string, unknown>".to_owned()
    }

    fn inline_object(&self, s: &Value, props: &serde_json::Map<String, Value>) -> String {
        let req: Vec<&str> = s
            .get("required")
            .and_then(Value::as_array)
            .map(|a| a.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let fields: Vec<String> = props
            .iter()
            .map(|(k, v)| {
                let opt = if req.contains(&k.as_str()) { "" } else { "?" };
                format!("{}{opt}: {}", ident(k), self.ty(v))
            })
            .collect();
        format!("{{ {} }}", fields.join("; "))
    }

    /// `export interface`/`type` for one definition.
    fn definition(&self, name: &str, s: &Value) -> String {
        let mut out = doc_comment(s, "");
        if let Some(props) = s.get("properties").and_then(Value::as_object)
            && !props.is_empty()
            && s.get("x-flyff-row").is_none()
        {
            let req: Vec<&str> = s
                .get("required")
                .and_then(Value::as_array)
                .map(|a| a.iter().filter_map(Value::as_str).collect())
                .unwrap_or_default();
            let _ = writeln!(out, "export interface {name} {{");
            for (k, v) in props {
                out.push_str(&doc_comment(v, "  "));
                let opt = if req.contains(&k.as_str()) { "" } else { "?" };
                let _ = writeln!(out, "  {}{opt}: {};", ident(k), self.ty(v));
            }
            out.push_str("}\n");
            return out;
        }
        let _ = writeln!(out, "export type {name} = {};", self.ty(s));
        out
    }
}

/// `true` when `ty` has a top-level `|` or `&` (an array of it needs parentheses).
fn needs_parens(ty: &str) -> bool {
    let mut depth = 0i32;
    for (i, c) in ty.char_indices() {
        match c {
            '[' | '{' | '(' | '<' => depth += 1,
            ']' | '}' | ')' | '>' => depth -= 1,
            '|' | '&' if depth == 0 => return true,
            '"' => {
                // a string literal: a quote inside it never opens a type; skip the rest conservatively
                let rest = ty.get(i + 1..).unwrap_or("");
                if rest.contains(" | ") && !rest.contains('"') {
                    return true;
                }
            }
            _ => {}
        }
    }
    false
}

fn union(parts: impl Iterator<Item = String>) -> String {
    let mut v: Vec<String> = Vec::new();
    for p in parts {
        if !v.contains(&p) {
            v.push(p);
        }
    }
    v.join(" | ")
}

/// A property name as a TypeScript identifier (quoted when it is not one).
fn ident(k: &str) -> String {
    let ok = !k.is_empty()
        && !k.starts_with(|c: char| c.is_ascii_digit())
        && k.chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if ok { k.to_owned() } else { quote(k) }
}

/// The files of `web/src/gen/bundles/`.
pub fn generate() -> Vec<TsFile> {
    let schemas = bundle_schemas();
    // merge the definitions of every document
    let mut defs: BTreeMap<String, Value> = BTreeMap::new();
    for (_, doc) in &schemas {
        if let Some(d) = doc.get("$defs").and_then(Value::as_object) {
            for (k, v) in d {
                defs.entry(k.clone()).or_insert_with(|| v.clone());
            }
        }
        // the manifest document is itself a type
    }
    if let Some((_, m)) = schemas.iter().find(|(n, _)| n == "manifest") {
        let mut m = m.clone();
        if let Some(o) = m.as_object_mut() {
            o.remove("$defs");
            o.remove("$schema");
        }
        defs.insert("BundleManifest".to_owned(), m);
    }
    let ctx = Ctx { defs: &defs };
    let mut types = String::from(HEADER);
    types.push_str("import type { RowTable } from \"./bundles\";\n\n");
    for (name, def) in &defs {
        if name.starts_with("RowTable_") {
            continue; // `RowTable<T>` of bundles.ts
        }
        let mut def = def.clone();
        if let Some(o) = def.as_object_mut() {
            o.remove("title");
        }
        types.push_str(&ctx.definition(name, &def));
        types.push('\n');
    }

    let mut bundles = String::from(HEADER);
    bundles.push_str("import type {\n");
    let data_types: Vec<(&str, String)> = catalog()
        .iter()
        .map(|s| (s.name, data_type_name(s.name)))
        .collect();
    for (_, t) in &data_types {
        let _ = writeln!(bundles, "  {t},");
    }
    bundles.push_str("} from \"./types\";\n\n");
    bundles.push_str("/** A columnar table (14 §10.2): `columns` names the fields, `rows` holds one cell array per row. `T` is the decoded row type (phantom). */\nexport interface RowTable<T> {\n  columns: string[];\n  rows: unknown[][];\n  /** Never set at runtime: carries `T` for `decodeRows<T>()`. */\n  readonly __row?: T;\n}\n\n");
    bundles.push_str("/** The version of the envelope and manifest shapes. */\nexport const BUNDLE_FORMAT = 1;\n\n");
    bundles.push_str("/** The 22 bundles in catalogue order (14 §10.4): name, schema version and load class. */\nexport const BUNDLES = [\n");
    for s in catalog() {
        let load = match s.load {
            super::types::LoadClass::Boot => "boot",
            super::types::LoadClass::Lazy => "lazy",
        };
        let _ = writeln!(
            bundles,
            "  {{ name: {}, schema: {}, load: {} }},",
            quote(s.name),
            s.schema,
            quote(load)
        );
    }
    bundles.push_str("] as const;\n\n");
    bundles.push_str("export type BundleName = (typeof BUNDLES)[number][\"name\"];\n\n");
    bundles
        .push_str("/** The `data` section of each bundle. */\nexport interface BundleDataMap {\n");
    for (n, t) in &data_types {
        let _ = writeln!(bundles, "  {}: {t};", quote(n));
    }
    bundles.push_str("}\n\n");
    bundles.push_str("/** The envelope of a bundle file. */\nexport interface BundleEnvelope<N extends BundleName> {\n  bundle: N;\n  schema: number;\n  data: BundleDataMap[N];\n}\n");

    let index = format!("{HEADER}export * from \"./bundles\";\nexport * from \"./types\";\n");
    vec![
        TsFile {
            name: "types.ts",
            text: types,
        },
        TsFile {
            name: "bundles.ts",
            text: bundles,
        },
        TsFile {
            name: "index.ts",
            text: index,
        },
    ]
}

/// The Rust data type of a bundle (`items` is `ItemsBundle`, `resdata-layouts` is `ResdataBundle`).
fn data_type_name(bundle: &str) -> String {
    match bundle {
        "item-ext" => "ItemExtBundle",
        "sfx-table" => "SfxTableBundle",
        "model-bounds" => "ModelBoundsBundle",
        "resdata-layouts" => "ResdataBundle",
        "ui-atlases" => "UiAtlasesBundle",
        other => {
            let mut c = other.chars();
            let first = c.next().map(|f| f.to_ascii_uppercase()).unwrap_or('X');
            return format!("{first}{}Bundle", c.as_str());
        }
    }
    .to_owned()
}

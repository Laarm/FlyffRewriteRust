//! The browser export of the command registry and the GM constants (Plan/23 §3.10, WP-GM-11):
//! [`gm_ts`] renders `web/src/gen/gm.ts` with the authority letters, the mode-flag constants and
//! `{name, aliases, minAuth, side, usage, help}` of every `Port` and `Client` row. The browser MUST NOT hard-code
//! command tables; the unit test `gm_ts_is_current` compares the committed file (`UPDATE_GOLDEN=1` rewrites it).

use super::{CmdSide, CmdStatus, table};
use flyff_common::gm::{Authority, ModeFlags};
use std::fmt::Write as _;

fn js_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('\'');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '\n' => out.push_str("\\n"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('\'');
    out
}

/// The text of `web/src/gen/gm.ts`.
pub fn gm_ts() -> String {
    let mut o = String::new();
    o.push_str(
        "// GENERATED by crates/flyff-game/src/gm/export.rs (Plan/23 §3.10, WP-GM-11). Do not edit: change the\n\
         // command table (tools/gen_gm_table.py) and regenerate with `UPDATE_GOLDEN=1 cargo test -p flyff-game gm_ts_is_current`.\n\n",
    );
    o.push_str("/** `AUTH_*` letters as their byte value (compared numerically, 23 §1.1). */\nexport const AUTHORITY = {\n");
    for (name, a) in [
        ("observer", Authority::OBSERVER),
        ("general", Authority::GENERAL),
        ("logChatting", Authority::LOG_CHATTING),
        ("journalist", Authority::JOURNALIST),
        ("helper", Authority::HELPER),
        ("gamemaster", Authority::GAMEMASTER),
        ("gamemaster2", Authority::GAMEMASTER2),
        ("gamemaster3", Authority::GAMEMASTER3),
        ("operator", Authority::OPERATOR),
        ("administrator", Authority::ADMINISTRATOR),
    ] {
        let _ = writeln!(o, "  {name}: {},", a.as_u8());
    }
    o.push_str("} as const;\n\n");
    o.push_str("/** `CMover::m_dwMode` bits (23 §2.1). */\nexport const MODE = {\n");
    for (name, m) in [
        ("MATCHLESS", ModeFlags::MATCHLESS),
        ("TRANSPARENT", ModeFlags::TRANSPARENT),
        ("ONEKILL", ModeFlags::ONEKILL),
        ("DONMOVE", ModeFlags::DONMOVE),
        ("SAYTALK", ModeFlags::SAYTALK),
        ("MATCHLESS2", ModeFlags::MATCHLESS2),
        ("NO_ATTACK", ModeFlags::NO_ATTACK),
        ("ITEM", ModeFlags::ITEM),
        ("COMMUNITY", ModeFlags::COMMUNITY),
        ("TALK", ModeFlags::TALK),
        ("SHOUTTALK", ModeFlags::SHOUTTALK),
        ("EXPUP_STOP", ModeFlags::EXPUP_STOP),
        ("GCWAR_RENDER_SKIP", ModeFlags::GCWAR_RENDER_SKIP),
        ("QUIZ_RENDER_SKIP", ModeFlags::QUIZ_RENDER_SKIP),
        ("DONTALK", ModeFlags::DONTALK),
    ] {
        let _ = writeln!(o, "  {name}: 0x{:08x},", m.bits());
    }
    o.push_str("} as const;\n\n");
    o.push_str(
        "export type GmSide = 'server' | 'client' | 'both';\n\n\
         export interface GmCommand {\n\
         \x20 /** The canonical English long name (shown by /help and the auto-complete list). */\n\
         \x20 name: string;\n\
         \x20 /** Legacy and new aliases (lower case). */\n\
         \x20 aliases: readonly string[];\n\
         \x20 /** The minimum authority byte (`AUTHORITY`). */\n\
         \x20 minAuth: number;\n\
         \x20 /** `client`: the browser executes it and never sends it. */\n\
         \x20 side: GmSide;\n\
         \x20 usage: string;\n\
         \x20 help: string;\n\
         \x20 /** The legacy table row (0 for a new command). */\n\
         \x20 row: number;\n\
         }\n\n",
    );
    o.push_str("/** Every implemented (`port`) and browser-handled (`client`) command in table order. */\nexport const GM_COMMANDS: readonly GmCommand[] = [\n");
    for s in table::COMMANDS {
        if !matches!(s.status, CmdStatus::Port | CmdStatus::Client) {
            continue;
        }
        let side = match s.side {
            CmdSide::Server => "server",
            CmdSide::Client => "client",
            CmdSide::Both => "both",
        };
        let aliases: Vec<String> = s
            .aliases
            .iter()
            .map(|a| js_str(&a.to_ascii_lowercase()))
            .collect();
        let _ = writeln!(
            o,
            "  {{ name: {}, aliases: [{}], minAuth: {}, side: '{}', usage: {}, help: {}, row: {} }},",
            js_str(s.name),
            aliases.join(", "),
            s.min_auth.as_u8(),
            side,
            js_str(s.usage),
            js_str(s.help),
            s.row
        );
    }
    o.push_str("];\n\n");
    o.push_str(
        "const BY_KEY: ReadonlyMap<string, GmCommand> = new Map(\n\
         \x20 GM_COMMANDS.flatMap((c) => [c.name, ...c.aliases].map((k) => [k.toLowerCase(), c] as const)),\n\
         );\n\n\
         /** Case-insensitive lookup of a command token (no leading slash); `undefined` when unknown (23 §3.3). */\n\
         export function findCommand(token: string): GmCommand | undefined {\n\
         \x20 return BY_KEY.get(token.toLowerCase());\n\
         }\n\n\
         /** The commands an `authority` byte may use: the auto-complete list of 23 §3.10 (browser-handled rows included). */\n\
         export function visibleCommands(authority: number): GmCommand[] {\n\
         \x20 return GM_COMMANDS.filter((c) => authority >= c.minAuth);\n\
         }\n",
    );
    o
}

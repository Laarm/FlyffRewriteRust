impl Config {
    /// The five sections owned by Plan/03 as one value (`SimFlags::from`, `DataOptions::from_rules`, …).
    pub fn rules(&self) -> RulesConfig {
        RulesConfig {
            features: self.features.clone(),
            gameplay: self.gameplay.clone(),
            rates: self.rates.clone(),
            events: self.events.clone(),
            fidelity: self.fidelity.clone(),
        }
    }

    /// The configuration as a TOML table (unset `Option` keys are absent).
    pub fn to_table(&self) -> toml::Table {
        match toml::Value::try_from(self) {
            Ok(toml::Value::Table(t)) => t,
            _ => toml::Table::new(),
        }
    }

    /// The effective value of a dotted key, `None` when unset or unknown.
    pub fn value_of(&self, dotted: &str) -> Option<toml::Value> {
        lookup(&self.to_table(), dotted).cloned()
    }
}

/// Looks up a dotted path in a TOML table.
pub fn lookup<'t>(table: &'t toml::Table, dotted: &str) -> Option<&'t toml::Value> {
    let mut parts = dotted.split('.');
    let mut cur = table.get(parts.next()?)?;
    for part in parts {
        cur = cur.as_table()?.get(part)?;
    }
    Some(cur)
}

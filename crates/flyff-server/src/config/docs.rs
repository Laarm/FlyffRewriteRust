//! Generated documentation artifacts of the configuration (Plan/03 WP-CORE-90, 10 §8.7): the commented
//! template, the typed browser projection `web/src/gen/config/clientFeatures.ts` and the key reference
//! `docs/config-keys.md`. [`artifacts`] computes them in memory; `cargo xtask config-docs [--check]` (through
//! `examples/config-docs.rs`) writes them or lists the stale ones, and `cargo xtask gen --check` includes it.

use super::keys::{Kind, SECTION_ORDER, all_keys, section_of};
use super::schema::Reload;
use super::template::{format_value, generate_template};
use super::{Config, lookup};
use flyff_common::config::{ClientFeatureConfig, KEY_REGISTRY, KeyClass, KeyMeta, KeySide};
use std::fmt::Write as _;

/// Repository-relative paths of the generated files.
pub const TEMPLATE_PATH: &str = "crates/flyff-server/assets/flyff.toml.example";
/// The typed `ClientFeatureConfig` for the browser.
pub const CLIENT_FEATURES_PATH: &str = "web/src/gen/config/clientFeatures.ts";
/// The key reference.
pub const KEY_DOCS_PATH: &str = "docs/config-keys.md";

/// The sections of `ClientFeatureConfig` with their interface names (`[rates]` and `[events]` have no client
/// keys; a test checks that no other section carries the C flag).
const CLIENT_SECTIONS: &[(&str, &str)] = &[
    ("features", "ClientFeatures"),
    ("gameplay", "ClientGameplay"),
    ("fidelity", "ClientFidelity"),
];

fn ts_type(m: &KeyMeta) -> String {
    let t: String = m.ty.chars().filter(|c| !c.is_whitespace()).collect();
    match t.as_str() {
        "bool" => "boolean".to_owned(),
        "String" => "string".to_owned(),
        "Vec<String>" => "string[]".to_owned(),
        "HitAttrRule" => "'legacy' | 'window'".to_owned(),
        "Option<f32>" => "number | null".to_owned(),
        _ => "number".to_owned(),
    }
}

fn ts_comment(m: &KeyMeta) -> String {
    let text = format!("{} ({})", m.doc, m.legacy).replace("*/", "* /");
    format!("  /** {text} */\n")
}

/// `web/src/gen/config/clientFeatures.ts`: one typed field per registry key with the C flag, grouped like
/// `flyff_common::config::ClientFeatureConfig`, plus the key list and the defaults.
pub fn client_features_ts() -> String {
    let mut out = String::from(
        "// GENERATED by `cargo xtask config-docs` from flyff_common::config::KEY_REGISTRY (Plan/03 §4.1).\n\
         // Do not edit: change the C flag of a key in crates/flyff-common/src/config/tables.rs and regenerate.\n\
         // The server sends this object in `GET /api/bootstrap` (docs 12/24); `DEFAULT_CLIENT_FEATURES` is the\n\
         // repack default used before the bootstrap answer arrives and by the /dev surfaces.\n\n",
    );
    for (section, iface) in CLIENT_SECTIONS {
        let _ = writeln!(out, "export interface {iface} {{");
        for m in KEY_REGISTRY
            .iter()
            .filter(|m| m.section == *section && m.client_delivered)
        {
            out.push_str(&ts_comment(m));
            let _ = writeln!(out, "  {}: {};", m.name, ts_type(m));
        }
        out.push_str("}\n\n");
    }
    out.push_str("export interface ClientFeatureConfig {\n");
    for (section, iface) in CLIENT_SECTIONS {
        let _ = writeln!(out, "  {section}: {iface};");
    }
    out.push_str("}\n\n");
    out.push_str("/** Every key that carries the C flag, as `section.key`. */\nexport const CLIENT_FEATURE_KEYS = [\n");
    for m in KEY_REGISTRY.iter().filter(|m| m.client_delivered) {
        let _ = writeln!(out, "  '{}',", m.key);
    }
    out.push_str("] as const;\n\n");
    let defaults = serde_json::to_string_pretty(&ClientFeatureConfig::default())
        .unwrap_or_else(|_| "{}".to_owned());
    let _ = writeln!(
        out,
        "export const DEFAULT_CLIENT_FEATURES: ClientFeatureConfig = {defaults};"
    );
    out
}

fn md_escape(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn side_name(s: KeySide) -> &'static str {
    match s {
        KeySide::Server => "server",
        KeySide::Client => "client",
        KeySide::Both => "server+client",
        KeySide::Sim => "sim",
    }
}

fn class_name(c: KeyClass) -> &'static str {
    match c {
        KeyClass::Startup => "startup",
        KeyClass::Runtime => "runtime",
        KeyClass::InitOnly => "init-only",
    }
}

/// `docs/config-keys.md`: every key of `flyff.toml` by section with type, default, values, class, owner and
/// legacy reference.
pub fn key_reference_md() -> String {
    let defaults = Config::default().to_table();
    let mut out = String::from(
        "# `flyff.toml` key reference\n\n\
         Generated by `cargo xtask config-docs` from the key tables of docs 03, 10 and 13; do not edit by hand.\n\
         The commented template with the same information is `crates/flyff-server/assets/flyff.toml.example`\n\
         (also printed by `flyff config default`). Precedence: built-in defaults, `flyff.toml`, environment\n\
         `FLYFF__SECTION__KEY`, command-line flags.\n",
    );
    for section in SECTION_ORDER {
        let keys: Vec<_> = all_keys()
            .iter()
            .filter(|k| section_of(k.key) == *section)
            .collect();
        if keys.is_empty() {
            continue;
        }
        let _ = write!(out, "\n## `[{section}]`\n\n");
        out.push_str("| Key | Type | Default | Values | Applies | Owner | Description |\n|---|---|---|---|---|---|---|\n");
        for k in keys {
            let name = k.key.rsplit('.').next().unwrap_or(k.key);
            let default = lookup(&defaults, k.key)
                .map_or_else(|| "unset".to_owned(), |v| format_value(v, k.ty));
            let meta = KEY_REGISTRY.iter().find(|m| m.key == k.key);
            let applies = match meta {
                Some(m) => {
                    let mut a = class_name(m.class).to_owned();
                    a.push_str(&format!(", {}", side_name(m.side)));
                    if m.client_delivered {
                        a.push_str(", C");
                    }
                    if m.reserved {
                        a.push_str(", reserved");
                    }
                    a
                }
                None => match k.reload {
                    Reload::Yes => "reload".to_owned(),
                    Reload::No => "restart".to_owned(),
                },
            };
            let mut desc = k.doc.to_owned();
            if let Some(l) = k.legacy {
                desc.push_str(&format!(" Legacy: {l}."));
            }
            if let Some(l) = k.ledger {
                desc.push_str(&format!(" Ledger: {l}."));
            }
            let ty = match k.kind {
                Kind::Str => "string",
                Kind::Int => "integer",
                Kind::Float => "float",
                Kind::Bool => "bool",
                Kind::StrArray => "[string]",
                Kind::TableArray => "[table]",
                Kind::Table => "table",
            };
            let _ = writeln!(
                out,
                "| `{name}` | {ty} | `{}` | {} | {applies} | {} | {} |",
                md_escape(&default),
                md_escape(&k.range.describe()),
                md_escape(k.owner),
                md_escape(&desc),
            );
        }
    }
    out
}

/// All generated artifacts as `(repository-relative path, content)`.
pub fn artifacts() -> Vec<(&'static str, String)> {
    vec![
        (TEMPLATE_PATH, generate_template()),
        (CLIENT_FEATURES_PATH, client_features_ts()),
        (KEY_DOCS_PATH, key_reference_md()),
    ]
}

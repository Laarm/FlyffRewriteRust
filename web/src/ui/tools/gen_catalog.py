#!/usr/bin/env python3
"""Generates web/src/ui/catalog.data.ts from Plan/42 section 19.4 (windows to build) and 19.6 (Drop/Defer).

Usage (run with `python3 -I`, from the repository root):
    python3 -I web/src/ui/tools/gen_catalog.py [PLAN_DOC] > web/src/ui/catalog.data.ts
    pnpm --dir web exec prettier --write src/ui/catalog.data.ts      # the generator does not wrap lines like prettier

The catalog rows are the machine-readable form of the plan tables (priority, milestone, WP, behaviour owner,
group letter). Edit the plan (or, after the UI scope gate, the gate ADR) and regenerate; never hand-edit the data.
"""

import re
import sys

if len(sys.argv) != 2:
    sys.exit("Usage: python3 -I web/src/ui/tools/gen_catalog.py PLAN_DOC")
DOC = sys.argv[1]

lines = open(DOC, encoding="utf8").read().split("\n")


def section(start_marker, end_marker):
    i0 = next(i for i, l in enumerate(lines) if l.startswith(start_marker))
    i1 = next(i for i, l in enumerate(lines) if i > i0 and l.startswith(end_marker))
    return lines[i0:i1]


built_rows = []
group = None
for l in section("### 19.4", "### 19.5"):
    m = re.match(r"\*\*([A-Z])\. ", l)
    if m:
        group = m.group(1)
        continue
    m = re.match(
        r"\| (APP_\w+) \((\d+)\) \| ([^|]*) \| ([^|]*) \| (P\d) \| (M\d) \| (UI-\d+) \| ([^|]*) \|", l
    )
    if m:
        name, num, size, skin, prio, ms, wp, owner = m.groups()
        built_rows.append((name, int(num), prio, ms, "WP-" + wp, group, owner.strip(), ""))
    elif l.startswith("| APP_"):
        sys.exit("unparsed catalog row: " + l[:120])

closed_rows = []
for l in section("### 19.6", "### 19.7"):
    m = re.match(r"\| (Drop|Defer) \| ([^|]*) \| (.*) \|$", l)
    if not m:
        continue
    prio, reason, names = m.groups()
    for name, num in re.findall(r"(APP_\w+) \((\d+)\)", names):
        closed_rows.append((name, int(num), prio, None, None, "-", "", reason.strip()))

rows = built_rows + closed_rows
ids = [r[1] for r in rows]
names = [r[0] for r in rows]
if len(set(ids)) != len(ids) or len(set(names)) != len(names):
    sys.exit("duplicate catalog entries")
if len(rows) != 365:
    sys.exit("expected 365 rows, got %d" % len(rows))
rows.sort(key=lambda r: r[1])


def q(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


out = []
out.append("// GENERATED by web/src/ui/tools/gen_catalog.py from Plan/42 section 19.4 and 19.6. DO NOT EDIT.")
out.append("// 365 layouts: priority, milestone, batch work package and behaviour owner (Plan/42 section 19).")
out.append("// The gate ADR of WP-UI-13 changes this table by regenerating it from the amended plan.")
out.append("")
out.append("import type { CatalogRow } from './catalog';")
out.append("")
out.append("/** [name, id, prio, milestone, wp, group, owner, note] sorted by APP id. */")
out.append("export const CATALOG_ROWS: readonly CatalogRow[] = [")
for name, num, prio, ms, wp, grp, owner, note in rows:
    out.append(
        "  [%s, %d, %s, %s, %s, %s, %s, %s],"
        % (q(name), num, q(prio), q(ms) if ms else "null", q(wp) if wp else "null", q(grp), q(owner), q(note))
    )
out.append("];")
print("\n".join(out))

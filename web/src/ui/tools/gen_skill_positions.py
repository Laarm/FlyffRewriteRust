#!/usr/bin/env python3
"""Generates `web/src/ui/windows/skills/skillPositions.ts` from `CWndSkillTreeEx::GetSkillPoint`
(`Source/_Interface/WndField.cpp`, the live switch after the commented-out first one): where each skill icon sits in the skill
tree window. Run `python3 -I web/src/ui/tools/gen_skill_positions.py` and `pnpm exec prettier --write` on the output.
The source is read from the required `$FLYFF_SOURCE` environment variable."""
import os
import re
import sys

src_root = os.environ.get("FLYFF_SOURCE")
if not src_root:
    sys.exit("Set FLYFF_SOURCE to the original Source directory.")
path = os.path.join(src_root, "_Interface", "WndField.cpp")
text = open(path, "rb").read().decode("cp1252", errors="replace").replace("\r", "")

start = text.index("BOOL CWndSkillTreeEx::GetSkillPoint")
end = text.index("void CWndSkillTreeEx::LoadTextureSkillicon")
body = text[start:end]
# the first switch is inside a block comment
live = body[body.index("*/") + 2 :]

rows = []
for m in re.finditer(
    r"case\s+(SI_\w+)\s*:\s*nRectX\s*=\s*(\d+)\s*,\s*nRectY\s*=\s*(\d+)\s*,\s*nJobKind\s*=\s*(MAX_\w+)\s*;", live
):
    name, x, y, kind = m.group(1), int(m.group(2)), int(m.group(3)), m.group(4)
    rows.append((name, x, y, {"MAX_EXPERT": 1, "MAX_PROFESSIONAL": 2}[kind]))
legend = []
for m in re.finditer(r"case\s+(SI_\w+)\s*:\s*nLegendSkill\s*=\s*(\d)\s*,\s*nJobKind\s*=\s*(MAX_\w+)\s*;", live):
    legend.append((m.group(1), int(m.group(2))))

if len(rows) != 140 or len(legend) != 16:
    print(f"unexpected counts: {len(rows)} tier skills, {len(legend)} legend skills", file=sys.stderr)
    sys.exit(1)

defs = open(
    os.path.join(os.path.dirname(__file__), "..", "..", "gen", "defs", "skill.ts"), encoding="utf-8"
).read()
for name, *_ in rows + legend:
    if f"export const {name} =" not in defs:
        print(f"missing define {name}", file=sys.stderr)
        sys.exit(1)

names = sorted({r[0] for r in rows} | {l[0] for l in legend})
out = []
out.append("// @generated by `web/src/ui/tools/gen_skill_positions.py` from CWndSkillTreeEx::GetSkillPoint")
out.append("// (`Source/_Interface/WndField.cpp:7333-7775`). DO NOT EDIT. Where every skill icon of the skill tree window sits:")
out.append("// expert and professional skills at (x, y) of the original's coordinate system (the window subtracts the section gap and adds the")
out.append("// section origin), master and hero skills in the custom placeholder `WIDC_CUSTOM5` / `WIDC_CUSTOM6`.")
out.append("import {")
for n in names:
    out.append(f"  {n},")
out.append("} from '../../../gen/defs/skill';")
out.append("")
out.append("/** `[x, y, kind]`: kind 1 = expert section, 2 = professional section (the `nJobKind` of the source). */")
out.append("export type TierPosition = readonly [x: number, y: number, kind: 1 | 2];")
out.append("")
out.append("/** The expert and professional skills (140). */")
out.append("export const TIER_POSITIONS: ReadonlyMap<number, TierPosition> = new Map([")
for name, x, y, kind in rows:
    out.append(f"  [{name}, [{x}, {y}, {kind}]],")
out.append("]);")
out.append("")
out.append("/** The master (0) and hero (1) skills: the placeholder they sit in (`WIDC_CUSTOM5` / `WIDC_CUSTOM6`). */")
out.append("export const LEGEND_POSITIONS: ReadonlyMap<number, 0 | 1> = new Map([")
for name, which in legend:
    out.append(f"  [{name}, {which}],")
out.append("]);")
out.append("")
dst = os.path.join(os.path.dirname(__file__), "..", "windows", "skills", "skillPositions.ts")
open(dst, "w", encoding="utf-8").write("\n".join(out))
print(f"wrote {dst}: {len(rows)} tier skills, {len(legend)} legend skills")

//! The Lua emitter (Plan/20 §5.4): one file per script, deterministic, LF line ends, no timestamps.
//!
//! ```lua
//! return {
//!   format = 1,
//!   script = "kepe_heron",
//!   defines = {},
//!   [0] = function(d) -- #auto
//!     d:Speak(d:NpcId(), 66) -- "Come to me if you want to do penance."
//!     d:SetScriptTimer(15)
//!   end,
//!   [5] = function(d) end, -- #questBegin
//! }
//! --[==[ UNREACHABLE ...
//! ]==]
//! ```

use crate::ast::{Call, Expr, Stmt};
use crate::dialog::{clip, text_comment};
use crate::inputs::Inputs;
use crate::model::{Func, Model, ScriptModel};
use std::collections::BTreeSet;
use std::fmt::Write as _;

/// The output format number (`format = 1` in every file and in `_transpile.toml`).
pub const FORMAT: u32 = 1;

/// The version of the emitter; bump it when the emitted text changes for the same input.
pub const TOOL_VERSION: &str = "1.0.0";

/// The Lua source of one script.
pub fn emit_script(model: &Model, script: &ScriptModel, inputs: &Inputs) -> String {
    let mut e = Emitter {
        out: String::new(),
        inputs,
    };
    e.script(model, script);
    e.out
}

struct Emitter<'a> {
    out: String,
    inputs: &'a Inputs,
}

impl Emitter<'_> {
    fn line(&mut self, indent: usize, text: &str) {
        for _ in 0..indent {
            self.out.push_str("  ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn script(&mut self, model: &Model, script: &ScriptModel) {
        let name = &script.name;
        let sha = self.inputs.npc_script_cpp.sha256.get(..16).unwrap_or("");
        self.line(0, &format!("-- content/npc/{name}.lua"));
        self.line(
            0,
            &format!(
                "-- Generated by npcscript-transpile format {FORMAT} from {} (sha256 {sha}). Do not edit.",
                self.inputs.npc_script_cpp.name
            ),
        );
        self.line(
            0,
            "-- Function keys are WorldDialog.txt key lines; numeric arguments of Say/Speak/AddKey/... are WorldDialog.txt line ids.",
        );
        if let Some(npcs) = &self.inputs.npcs {
            let bound: Vec<String> = npcs
                .iter()
                .filter(|n| &n.dialog_key == name)
                .map(|n| format!("{} ({})", n.key, n.dialog_file))
                .collect();
            let text = if bound.is_empty() {
                "no NPC of character*.inc".to_owned()
            } else {
                bound.join(", ")
            };
            self.line(0, &format!("-- Bound by: {}", clip(&text, 400)));
        }
        self.line(0, "return {");
        self.line(1, &format!("format = {FORMAT},"));
        self.line(1, &format!("script = {},", lua_str(name)));
        let defines = defines_of(model, script);
        self.defines(&defines);
        for (&key, &idx) in &script.reachable {
            if let Some(f) = model.funcs.get(idx) {
                self.function(key, f, None);
            }
        }
        self.line(0, "}");
        if !script.unreachable.is_empty() {
            self.line(
                0,
                "--[==[ UNREACHABLE: the original server never calls these (KEEP-QUIRK D20-05, Plan/20 sec. 5.3 step 4)",
            );
            for &idx in &script.unreachable {
                if let Some(f) = model.funcs.get(idx) {
                    let reason = f.reach.reason();
                    self.function(f.key, f, Some(&reason));
                }
            }
            self.line(0, "]==]");
        }
    }

    fn defines(&mut self, defines: &BTreeSet<String>) {
        if defines.is_empty() {
            self.line(1, "defines = {},");
            return;
        }
        let quoted: Vec<String> = defines.iter().map(|n| lua_str(n)).collect();
        let one = format!("defines = {{ {} }},", quoted.join(", "));
        if one.len() <= 100 {
            self.line(1, &one);
        } else {
            self.line(1, "defines = {");
            for q in quoted {
                self.line(2, &format!("{q},"));
            }
            self.line(1, "},");
        }
    }

    fn function(&mut self, key: u32, f: &Func, unreachable: Option<&str>) {
        let key_text = clip(self.inputs.text(i64::from(key)), 60);
        let tag = match unreachable {
            Some(reason) => format!(" -- {key_text}; {reason}"),
            None => format!(" -- {key_text}"),
        };
        if f.body().is_empty() {
            self.line(1, &format!("[{key}] = function(d) end,{tag}"));
            return;
        }
        self.line(1, &format!("[{key}] = function(d){tag}"));
        let mut counter = 0u32;
        self.stmts(f.body(), 2, &mut counter);
        self.line(1, "end,");
    }

    fn stmts(&mut self, stmts: &[Stmt], indent: usize, counter: &mut u32) {
        for s in stmts {
            match s {
                Stmt::Call(c) => {
                    let mut text = lua_call(c);
                    let comment = self.call_comment(c);
                    if !comment.is_empty() {
                        text.push_str(" -- ");
                        text.push_str(&comment);
                    }
                    self.line(indent, &text);
                }
                Stmt::If {
                    cond, then, els, ..
                } => {
                    self.if_chain(cond, then, els, indent, "if", counter);
                    self.line(indent, "end");
                }
                Stmt::Switch {
                    random_arg, cases, ..
                } => {
                    *counter += 1;
                    let var = format!("r{counter}");
                    self.line(indent, "do");
                    self.line(indent + 1, &format!("local {var} = d:Random({random_arg})"));
                    for (i, case) in cases.iter().enumerate() {
                        let test: Vec<String> = case
                            .labels
                            .iter()
                            .map(|l| format!("{var} == {l}"))
                            .collect();
                        let kw = if i == 0 { "if" } else { "elseif" };
                        self.line(indent + 1, &format!("{kw} {} then", test.join(" or ")));
                        self.stmts(&case.body, indent + 2, counter);
                    }
                    if !cases.is_empty() {
                        self.line(indent + 1, "end");
                    }
                    self.line(indent, "end");
                }
            }
        }
    }

    fn if_chain(
        &mut self,
        cond: &Expr,
        then: &[Stmt],
        els: &[Stmt],
        indent: usize,
        keyword: &str,
        counter: &mut u32,
    ) {
        self.line(indent, &format!("{keyword} {} then", lua_expr(cond)));
        self.stmts(then, indent + 1, counter);
        match els {
            [] => {}
            [
                Stmt::If {
                    cond: c2,
                    then: t2,
                    els: e2,
                    ..
                },
            ] => self.if_chain(c2, t2, e2, indent, "elseif", counter),
            other => {
                self.line(indent, "else");
                self.stmts(other, indent + 1, counter);
            }
        }
    }

    /// The trailing comment of a statement call: the resolved text of its literal text-id arguments.
    fn call_comment(&self, c: &Call) -> String {
        let mut parts = Vec::new();
        for i in c.helper.text_args(c.args.len()) {
            if let Some(Expr::Int(id)) = c.args.get(i) {
                parts.push(text_comment(self.inputs, *id));
            }
        }
        parts.join(" / ")
    }
}

/// The define names a script's reachable functions use (`defines = { ... }`).
pub fn defines_of(model: &Model, script: &ScriptModel) -> BTreeSet<String> {
    script
        .reachable
        .values()
        .filter_map(|i| model.funcs.get(*i))
        .filter_map(|f| f.parsed.as_ref())
        .flat_map(|p| p.consts.iter().cloned())
        .collect()
}

/// `d:Name(args)`.
pub fn lua_call(c: &Call) -> String {
    let mut s = String::new();
    let _ = write!(s, "d:{}(", c.helper.name);
    for (i, a) in c.args.iter().enumerate() {
        if i > 0 {
            s.push_str(", ");
        }
        s.push_str(&lua_expr(a));
    }
    s.push(')');
    s
}

/// A Lua expression for a typed AST node.
pub fn lua_expr(e: &Expr) -> String {
    match e {
        Expr::Int(v) => v.to_string(),
        Expr::Float(t, _) => t.clone(),
        Expr::Const(n) => format!("C.{n}"),
        Expr::Call(c) => lua_call(c),
        Expr::Num(b) => format!("({} and 1 or 0)", lua_expr(b)),
        Expr::Not(b) => format!("not ({})", lua_expr(b)),
        Expr::And(a, b) => format!("{} and {}", and_operand(a), and_operand(b)),
        Expr::Or(a, b) => format!("{} or {}", lua_expr(a), lua_expr(b)),
        Expr::Rel(op, a, b) => format!("{} {} {}", lua_expr(a), op.lua(), lua_expr(b)),
    }
}

fn and_operand(e: &Expr) -> String {
    match e {
        Expr::Or(..) => format!("({})", lua_expr(e)),
        other => lua_expr(other),
    }
}

/// A double-quoted Lua string literal.
pub fn lua_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            c if c.is_control() => {
                let _ = write!(out, "\\{}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
